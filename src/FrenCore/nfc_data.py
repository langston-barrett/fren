"""Writes `NfcData.lean`, the Unicode tables that `Nfc.lean` reads.

Run it with a Python whose `unicodedata` has the Unicode version that the
tables should have, from this directory:

    python3 -I nfc_data.py > NfcData.lean
"""

import sys
import unicodedata

LIMIT = 0x110000
# The version that `Nfc.lean` and the Reqs name. An older Python, such as
# 3.9 with Unicode 13.0, would write other tables without notice.
VERSION = "15.0.0"


def ranges(pred):
    """The maximal ranges of code points with the same value of `pred`,
    other than `None`, as (first, last, value)."""
    out = []
    for cp in range(LIMIT):
        v = pred(cp)
        if v is not None and out and out[-1][1] == cp - 1 and out[-1][2] == v:
            out[-1] = (out[-1][0], cp, v)
        elif v is not None:
            out.append((cp, cp, v))
    return out


def lean_string(name, doc, entries):
    lines = []
    line = ""
    for e in entries:
        if len(line) + len(e) + 1 > 100:
            lines.append(line)
            line = ""
        line += e + " "
    lines.append(line)
    body = "\\\n  ".join(lines)
    return f'/-- {doc} -/\ndef {name} : String :=\n  "{body}"\n'


def main():
    assert unicodedata.unidata_version == VERSION, (
        f"unicodedata has Unicode {unicodedata.unidata_version}, not {VERSION}")
    combining = ranges(lambda cp: unicodedata.combining(chr(cp)) or None)
    assigned = ranges(lambda cp: True if unicodedata.category(chr(cp)) != "Cn" else None)
    decompositions = []
    excluded = []
    for cp in range(LIMIT):
        c = chr(cp)
        d = unicodedata.decomposition(c)
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        decompositions.append([cp] + parts)
        # A pair that NFC does not compose back: an exclusion, or a
        # decomposition that starts with a non-starter.
        if len(parts) == 2 and unicodedata.normalize("NFC", c) != c:
            excluded.append(cp)
    h = lambda n: format(n, "x")
    out = sys.stdout
    out.write(f"""/-!
# Unicode tables for NFC

Generated by `nfc_data.py` from Unicode {unicodedata.unidata_version}, which
its Python's `unicodedata` has: do not edit by hand. Each table is a string
of entries separated by spaces, of fields in hexadecimal separated by
commas, which `Nfc.lean` reads once.
-/

namespace Fren.Core.NfcData

def unicodeVersion : String := "{unicodedata.unidata_version}"

""")
    out.write(lean_string(
        "combiningClasses",
        "The canonical combining classes other than 0: `first,last,class`.",
        [f"{h(a)},{h(b)},{h(v)}" for a, b, v in combining]))
    out.write("\n")
    out.write(lean_string(
        "decompositions",
        "The canonical decompositions, one level, but for Hangul syllables: `char,first[,second]`.",
        [",".join(h(n) for n in d) for d in decompositions]))
    out.write("\n")
    out.write(lean_string(
        "exclusions",
        "The characters with a decomposition of two that NFC does not compose.",
        [h(cp) for cp in excluded]))
    out.write("\n")
    out.write(lean_string(
        "assigned",
        "The ranges of assigned code points, of any category but `Cn`: `first,last`.",
        [f"{h(a)},{h(b)}" for a, b, _ in assigned]))
    out.write("\nend Fren.Core.NfcData\n")


if __name__ == "__main__":
    main()
